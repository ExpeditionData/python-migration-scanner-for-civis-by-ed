"""app/ and common/ run in the Service image, which has civis 2.7.1.

This test fails if code in those packages calls a civis endpoint method, a
civis.io or civis.utils function, or an APIClient argument that does not exist
in civis 2.7.1. For example, client.users.get_me() fails here because 2.7.1
only has list_me.

The list of what exists in 2.7.1 is tests/fixtures/civis_2_7_1_api.json,
generated by tools/build_civis_api_fixture.py from the civis 2.7.1 wheel.

To skip a line that only looks like a civis call (for example Flask's
request.files.get), add the comment "# civis-compat: not-civis" to that line.
"""

from __future__ import annotations

import ast
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "civis_2_7_1_api.json"
CHECKED_PACKAGES = ("app", "common")
SKIP_MARKER = "civis-compat: not-civis"


def load_api() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _alias_map(tree: ast.AST) -> dict[str, str]:
    aliases: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    aliases[alias.asname] = alias.name
                else:
                    top = alias.name.split(".")[0]
                    aliases[top] = top
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            for alias in node.names:
                aliases[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return aliases


def _dotted(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = _dotted(node.value)
        return f"{base}.{node.attr}" if base else None
    return None


def _resolve(dotted: str, aliases: dict[str, str]) -> str:
    head, _, rest = dotted.partition(".")
    if head in aliases:
        head = aliases[head]
    return f"{head}.{rest}" if rest else head


def _check_keywords(call: ast.Call, params: dict, label: str, problems: list[str]) -> None:
    if params["var_keyword"]:
        return
    allowed = set(params["keyword"])
    for kw in call.keywords:
        if kw.arg is not None and kw.arg not in allowed:
            problems.append(f"{label}: argument '{kw.arg}' does not exist in civis 2.7.1")


def find_problems(source: str, filename: str, api: dict) -> list[str]:
    tree = ast.parse(source, filename=filename)
    lines = source.splitlines()
    aliases = _alias_map(tree)
    endpoints = api["endpoints"]
    problems: list[str] = []

    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        line_text = lines[node.lineno - 1] if node.lineno <= len(lines) else ""
        if SKIP_MARKER in line_text:
            continue
        where = f"{filename}:{node.lineno}"
        func = node.func
        dotted = _dotted(func)
        resolved = _resolve(dotted, aliases) if dotted else None

        if resolved and resolved.startswith(("civis.io.", "civis.utils.")):
            module, name = resolved.split(".")[1], resolved.split(".")[-1]
            functions = api[module]
            if name not in functions:
                problems.append(f"{where}: civis.{module}.{name} does not exist in civis 2.7.1")
            else:
                _check_keywords(node, functions[name], f"{where}: civis.{module}.{name}", problems)
            continue

        if resolved == "civis.APIClient":
            _check_keywords(node, api["api_client"]["init"], f"{where}: civis.APIClient", problems)
            continue

        # <anything>.io.<function>(...), for example self.io.read_civis_sql() with civis.io injected
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Attribute) and func.value.attr in ("io", "utils"):
            module, name = func.value.attr, func.attr
            functions = api[module]
            if name not in functions:
                problems.append(f"{where}: civis.{module}.{name} does not exist in civis 2.7.1")
            else:
                _check_keywords(node, functions[name], f"{where}: civis.{module}.{name}", problems)
            continue

        # <anything>.<endpoint>.<method>(...), for example client.users.list_me()
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Attribute):
            endpoint, method = func.value.attr, func.attr
            if endpoint in endpoints:
                methods = endpoints[endpoint]
                if method not in methods:
                    problems.append(f"{where}: client.{endpoint}.{method} does not exist in civis 2.7.1")
                else:
                    _check_keywords(node, methods[method], f"{where}: client.{endpoint}.{method}", problems)
    return problems


def checked_files() -> list[Path]:
    files = []
    for package in CHECKED_PACKAGES:
        files.extend(sorted((ROOT / package).rglob("*.py")))
    return files


def test_fixture_is_civis_2_7_1():
    api = load_api()
    assert api["civis_version"] == "2.7.1"
    assert "list_me" in api["endpoints"]["users"]
    assert "get_me" not in api["endpoints"]["users"]


def test_app_and_common_only_use_civis_2_7_1_api():
    api = load_api()
    problems = []
    for path in checked_files():
        rel = path.relative_to(ROOT).as_posix()
        problems.extend(find_problems(path.read_text(encoding="utf-8"), rel, api))
    assert not problems, "\n".join(problems)


@pytest.mark.parametrize(
    "source, expected",
    [
        ("client.users.get_me()", "client.users.get_me does not exist"),
        ("client.scripts.get_python3_git(5)", "client.scripts.get_python3_git does not exist"),
        ("import civis\ncivis.io.no_such_function()", "civis.io.no_such_function does not exist"),
        (
            "from civis.io import query_civis\nquery_civis('select 1', 'db', sql_params_arguments={})",
            "argument 'sql_params_arguments' does not exist",
        ),
        ("import civis as c\nc.APIClient(not_an_arg=1)", "argument 'not_an_arg' does not exist"),
        ("client.scripts.post_containers_runs(1, bogus=2)", "argument 'bogus' does not exist"),
        ("self.io.query_civis('select 1', 'db', sql_params_arguments={})", "argument 'sql_params_arguments' does not exist"),
        ("self.io.no_such_helper()", "civis.io.no_such_helper does not exist"),
    ],
)
def test_checker_catches_calls_missing_from_2_7_1(source, expected):
    problems = find_problems(source, "example.py", load_api())
    assert any(expected in p for p in problems), problems


@pytest.mark.parametrize(
    "source",
    [
        "client.users.list_me()",
        "client.scripts.post_containers_runs(1)",
        "client.scripts.list_containers_runs_logs(1, 2, limit=100)",
        "import civis\ncivis.io.read_civis_sql('select 1', 'db', return_as='list')",
        "import civis\ncivis.io.query_civis('select 1', database='db')",
        "import civis\ncivis.APIClient()",
        "request.files.get('f', bogus=1)  # civis-compat: not-civis",
        "request.args.get('page')",
    ],
)
def test_checker_accepts_calls_that_exist_in_2_7_1(source):
    assert find_problems(source, "example.py", load_api()) == []
